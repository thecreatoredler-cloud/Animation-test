#!/usr/bin/env python3
"""Regenerate references/api_quickref.md from the library source (signatures + first doc line).
Run after changing any library module:  python3 scripts/gen_api_ref.py"""
import ast, os
HERE = os.path.dirname(os.path.abspath(__file__))
MODS = ["blender_setup", "scene_builder", "materials", "lighting_tools", "camera_tools", "animation_tools"]
out = ["# API quick reference (generated by scripts/gen_api_ref.py; do not edit by hand)", "",
       "Import in a shot file: `import scene_builder as sb, materials as M, lighting_tools as lt, "
       "camera_tools as ct, animation_tools as at`. Units are metres, frames at 30 fps.", ""]
for m in MODS:
    tree = ast.parse(open(os.path.join(HERE, m + ".py")).read())
    out += [f"## {m}", ""]
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and not node.name.startswith("_"):
            if isinstance(node, ast.ClassDef):
                init = next((n for n in node.body if isinstance(n, ast.FunctionDef) and n.name == "__init__"), None)
                sig = ast.unparse(init.args).replace("self, ", "") if init else ""
            else:
                sig = ast.unparse(node.args)
            doc = (ast.get_docstring(node) or "").strip().split("\n")[0]
            out.append(f"- `{node.name}({sig})`" + (f": {doc}" if doc else ""))
    out.append("")
open(os.path.join(os.path.dirname(HERE), "references", "api_quickref.md"), "w").write("\n".join(out))
print("written references/api_quickref.md")
